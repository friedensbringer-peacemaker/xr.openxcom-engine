Canvas::Canvas(int width, int height) : _width(width), _height(height), _pixels(static_cast<size_t>(width) * height * 4, 0)
{
}

void Canvas::fill(int x0, int y0, int w, int h, uint32_t rgb)
{
	const int x1 = std::min(_width, x0 + w), y1 = std::min(_height, y0 + h);
	for (int y = std::max(0, y0); y < y1; ++y)
		for (int x = std::max(0, x0); x < x1; ++x)
		{
			uint8_t *p = &_pixels[(static_cast<size_t>(y) * _width + x) * 4];
			p[0] = (rgb >> 16) & 0xFF;
			p[1] = (rgb >> 8) & 0xFF;
			p[2] = rgb & 0xFF;
			p[3] = 0xFF;
		}
}

void Canvas::text(const std::string &utf8, float x, float centerY, int maxScale, float maxWidth, uint32_t rgb, bool centered)
{
	const std::string glyphs = toGlyphs(utf8);
	const int count = static_cast<int>(glyphs.size());
	if (count == 0)
		return;
	int scale = maxScale;
	while (scale > 1 && count * 6 * scale - scale > maxWidth)
		--scale;
	const int textW = count * 6 * scale - scale, textH = 7 * scale;
	int px = static_cast<int>(centered ? x - textW / 2.0f : x);
	const int py = static_cast<int>(centerY) - textH / 2;
	for (char c : glyphs)
	{
		const uint8_t *rows = glyph(c);
		for (int r = 0; r < 7; ++r)
			for (int col = 0; col < 5; ++col)
				if (rows[r] & (0x10 >> col))
					fill(px + col * scale, py + r * scale, scale, scale, rgb);
		px += 6 * scale;
	}
}

int buttonAt(const std::vector<UiButton> &buttons, int width, int height, float u, float v)
{
	const float px = u * width, py = v * height, slack = 4.0f;
	for (size_t i = 0; i < buttons.size(); ++i)
	{
		const UiButton &b = buttons[i];
		if (px >= b.x - slack && px < b.x + b.w + slack && py >= b.y - slack && py < b.y + b.h + slack)
			return static_cast<int>(i);
	}
	return -1;
}

