/// UTF-8 -> glyph codes: upper case ASCII, umlauts, degree sign; glyph codes (< 0x20) pass through.
std::string toGlyphs(const std::string &utf8)
{
	std::string out;
	for (size_t i = 0; i < utf8.size(); ++i)
	{
		const unsigned char c = static_cast<unsigned char>(utf8[i]);
		if (c < 0x80)
		{
			out += (c >= 'a' && c <= 'z') ? static_cast<char>(c - 'a' + 'A') : static_cast<char>(c);
			continue;
		}
		if (i + 1 >= utf8.size())
			break;
		const unsigned char d = static_cast<unsigned char>(utf8[i + 1]);
		++i;
		if (c == 0xC3 && (d == 0x84 || d == 0xA4))
			out += GlyphAe;
		else if (c == 0xC3 && (d == 0x96 || d == 0xB6))
			out += GlyphOe;
		else if (c == 0xC3 && (d == 0x9C || d == 0xBC))
			out += GlyphUe;
		else if (c == 0xC3 && d == 0x9F)
			out += GlyphSz;
		else if (c == 0xC2 && d == 0xB0)
			out += GlyphDegree;
		else
			out += '?';
	}
	return out;
}

